import type { RunReportArtifact } from "@issuepilot/shared-contracts";

import { renderHandoffNote } from "../reports/render.js";

export interface ReconcileInput {
  runId: string;
  iid: number;
  branch: string;
  baseBranch: string;
  workspacePath: string;
  attempt: number;
  agentSummary?: string | undefined;
  agentValidation?: string | undefined;
  agentRisks?: string | undefined;
  noCodeChangeReason?: string | undefined;
  issueUrl: string;
  issueIdentifier: string;
  runningLabel: string;
  handoffLabel: string;
  reworkLabel: string;
  git: GitSlice;
  gitlab: GitLabReconcileSlice;
  onEvent: (event: ReconcileEvent) => void;
  /**
   * V2.5 Command Center: when present, the handoff workpad note is rendered
   * from the run report artifact instead of the legacy `buildHandoffNote`
   * fallback. Daemon-driven reconcile passes the latest report so a single
   * fact source covers dashboard, notes and exports.
   */
  report?: RunReportArtifact | undefined;
  /**
   * V4.1 Workflow Spine: V2.x runs (single issue → single MR) use the
   * default `"active"` mode where reconcile transitions the parent Issue
   * label to `human-review` and writes the per-run workpad handoff note.
   *
   * V4.1 synthetic task runs share the dispatch/reconcile path but do NOT
   * own the parent Issue lifecycle — that responsibility belongs to the
   * WorkItem aggregator (`work-items/handoff.ts`). Setting this to
   * `"suppressed"` keeps all task-level side-effects (push, create/update
   * MR, return mergeRequest metadata) intact while skipping the parent
   * Issue label transition and the workpad note write.
   *
   * Defaults to `"active"` to preserve V2.x behaviour when callers omit
   * the flag.
   */
  parentIssueLabelMode?: "active" | "suppressed" | undefined;
}

/**
 * Side-effects metadata returned to the daemon so it can update the run
 * report with the handoff note id and the MR coordinates.
 */
export interface ReconcileResult {
  mergeRequest?: { iid: number; webUrl?: string };
  handoffNoteId?: number;
  hadNewCommits: boolean;
}

export interface ReconcileEvent {
  type: string;
  runId: string;
  ts: string;
  detail: Record<string, unknown>;
}

interface GitSlice {
  hasNewCommits(cwd: string, baseBranch: string): Promise<boolean>;
  push(cwd: string, branch: string): Promise<void>;
}

interface GitLabReconcileSlice {
  findMergeRequest(sourceBranch: string): Promise<{
    iid: number;
    title: string;
    description: string;
    webUrl?: string;
  } | null>;
  createMergeRequest(opts: {
    sourceBranch: string;
    targetBranch: string;
    title: string;
    description: string;
  }): Promise<{ iid: number; webUrl?: string }>;
  updateMergeRequest(
    mrIid: number,
    opts: { title?: string; description?: string },
  ): Promise<void>;
  findWorkpadNote(
    issueIid: number,
    marker: string,
  ): Promise<{ id: number; body: string } | null>;
  createNote(issueIid: number, body: string): Promise<{ id: number }>;
  updateNote(issueIid: number, noteId: number, body: string): Promise<void>;
  transitionLabels(
    iid: number,
    opts: { add: string[]; remove: string[] },
  ): Promise<void>;
}

function buildMrBody(input: ReconcileInput): string {
  const summary =
    input.agentSummary ||
    "Codex completed without a structured summary; see commits.";
  const validation = input.agentValidation || "(no validation summary)";
  const risks = input.agentRisks || "(none reported)";

  return [
    `Issue: ${input.issueUrl}`,
    "",
    "## Implementation summary",
    summary,
    "",
    "## Validation",
    validation,
    "",
    "## Risks",
    risks,
    "",
    "---",
    `Generated by IssuePilot for ${input.issueIdentifier}, attempt ${input.attempt}.`,
  ].join("\n");
}

function fallbackText(value: string | undefined, fallback: string): string {
  const trimmed = value?.trim();
  return trimmed ? trimmed : fallback;
}

function mrLine(mr: { iid: number; webUrl?: string } | null): string {
  if (!mr) return "not created";
  return mr.webUrl ? `!${mr.iid} ${mr.webUrl}` : `!${mr.iid}`;
}

function buildHandoffNote(
  input: ReconcileInput,
  mr: { iid: number; webUrl?: string } | null,
): string {
  const summary = fallbackText(
    input.agentSummary,
    input.noCodeChangeReason
      ? `No code changes: ${input.noCodeChangeReason}`
      : "Codex completed without a structured summary; see commits.",
  );
  const validation = fallbackText(
    input.agentValidation,
    input.noCodeChangeReason
      ? "No validation command was reported for this no-code-change run."
      : "(no validation summary)",
  );
  const risks = fallbackText(input.agentRisks, "None reported.");

  return [
    `<!-- issuepilot:run:${input.runId} -->`,
    "## IssuePilot handoff",
    "",
    `- Status: ${input.handoffLabel}`,
    `- Run: \`${input.runId}\``,
    `- Attempt: ${input.attempt}`,
    `- Branch: \`${input.branch}\``,
    `- MR: ${mrLine(mr)}`,
    "",
    "### What changed",
    summary,
    "",
    "### Validation",
    validation,
    "",
    "### Risks / follow-ups",
    risks,
    "",
    "### Next action",
    `Review and merge the MR, or move this Issue to \`${input.reworkLabel}\` if changes are required.`,
  ].join("\n");
}

function now(): string {
  return new Date().toISOString();
}

/**
 * Slice of {@link ReconcileInput} that {@link mergeAgentHandoffIntoReport}
 * actually reads. We expose a narrow slice so the daemon writeback path
 * does not have to synthesise an entire `ReconcileInput` (with git/gitlab
 * stubs) just to merge a few fields.
 */
export interface ReportHandoffMergeInput {
  agentSummary?: string | undefined;
  agentValidation?: string | undefined;
  agentRisks?: string | undefined;
  noCodeChangeReason?: string | undefined;
  reworkLabel: string;
}

/**
 * Merge the freshest agent / no-code-change fields onto the seed
 * `RunReportArtifact` before we render the handoff note. The seed written
 * at claim time only has placeholder strings — without this merge the
 * note posted to GitLab would render "not reported" even when the agent
 * produced a real summary, validation, or no-code-change explanation
 * (see V2.5 review C1/C2). The function is intentionally pure so the
 * same merged report can be reused by daemon code when it later writes
 * the artifact back to the report store.
 */
export function mergeAgentHandoffIntoReport(
  report: RunReportArtifact,
  input: ReportHandoffMergeInput,
  mr: { iid: number; webUrl?: string } | null,
): RunReportArtifact {
  const noCodeChangeReason = input.noCodeChangeReason?.trim();
  const summary = fallbackText(
    input.agentSummary,
    noCodeChangeReason
      ? `No code changes: ${noCodeChangeReason}`
      : report.handoff.summary,
  );
  const validation = input.agentValidation?.trim()
    ? [input.agentValidation.trim()]
    : noCodeChangeReason && report.handoff.validation.length === 0
      ? ["No validation command was reported for this no-code-change run."]
      : report.handoff.validation;
  const risks = input.agentRisks?.trim()
    ? [{ level: "medium" as const, text: input.agentRisks.trim() }]
    : report.handoff.risks;
  const nextAction =
    report.handoff.nextAction && report.handoff.nextAction !== "not reported"
      ? report.handoff.nextAction
      : `Review and merge the MR, or move this Issue to \`${input.reworkLabel}\` if changes are required.`;

  return {
    ...report,
    handoff: {
      ...report.handoff,
      summary,
      validation,
      risks,
      nextAction,
    },
    ...(mr
      ? {
          mergeRequest: {
            iid: mr.iid,
            url: mr.webUrl ?? "",
            state: "opened" as const,
          },
        }
      : {}),
  };
}

function renderNoteBody(
  input: ReconcileInput,
  mr: { iid: number; webUrl?: string } | null,
): string {
  if (input.report) {
    const reportForNote = mergeAgentHandoffIntoReport(input.report, input, mr);
    return renderHandoffNote(reportForNote, {
      handoffLabel: input.handoffLabel,
    });
  }
  return buildHandoffNote(input, mr);
}

export async function reconcile(input: ReconcileInput): Promise<ReconcileResult> {
  const suppressParentIssue = input.parentIssueLabelMode === "suppressed";

  const hasCommits = await input.git.hasNewCommits(
    input.workspacePath,
    input.baseBranch,
  );

  if (!hasCommits) {
    const noCodeChangeReason = input.noCodeChangeReason?.trim();
    input.onEvent({
      type: "reconcile_no_commits",
      runId: input.runId,
      ts: now(),
      detail: { branch: input.branch },
    });

    if (!noCodeChangeReason) {
      throw new Error(
        `Reconcile found no new commits on branch ${input.branch} and no explicit no-code-change reason.`,
      );
    }

    // V4.1 synthetic task runs do not own the parent Issue workpad note or
    // the parent Issue workflow label. Bail out before touching either; the
    // WorkItem aggregator (`work-items/handoff.ts`) will write the parent
    // handoff once every required task is done.
    if (suppressParentIssue) {
      return { hadNewCommits: false };
    }

    const marker = `<!-- issuepilot:run:${input.runId} -->`;
    const existingNote = await input.gitlab.findWorkpadNote(input.iid, marker);
    const noteBody = renderNoteBody({ ...input, noCodeChangeReason }, null);

    let handoffNoteId: number | undefined;
    if (!existingNote) {
      const note = await input.gitlab.createNote(input.iid, noteBody);
      handoffNoteId = note.id;
      input.onEvent({
        type: "gitlab_workpad_note_created",
        runId: input.runId,
        ts: now(),
        detail: { noteId: note.id, branch: input.branch },
      });
    } else {
      await input.gitlab.updateNote(input.iid, existingNote.id, noteBody);
      handoffNoteId = existingNote.id;
      input.onEvent({
        type: "gitlab_workpad_note_updated",
        runId: input.runId,
        ts: now(),
        detail: { noteId: existingNote.id, branch: input.branch },
      });
    }

    await transitionToHandoff(input);
    return {
      hadNewCommits: false,
      ...(handoffNoteId !== undefined ? { handoffNoteId } : {}),
    };
  }

  await input.git.push(input.workspacePath, input.branch);
  input.onEvent({
    type: "gitlab_push",
    runId: input.runId,
    ts: now(),
    detail: { branch: input.branch },
  });

  const existingMr = await input.gitlab.findMergeRequest(input.branch);
  const mrBody = buildMrBody(input);

  let handoffMr: { iid: number; webUrl?: string };
  if (!existingMr) {
    const mr = await input.gitlab.createMergeRequest({
      sourceBranch: input.branch,
      targetBranch: input.baseBranch,
      title: `[IssuePilot] ${input.issueIdentifier}`,
      description: mrBody,
    });
    handoffMr = mr;
    input.onEvent({
      type: "gitlab_mr_created",
      runId: input.runId,
      ts: now(),
      detail: { mrIid: mr.iid, branch: input.branch },
    });
  } else {
    await input.gitlab.updateMergeRequest(existingMr.iid, {
      description: mrBody,
    });
    handoffMr = existingMr;
    input.onEvent({
      type: "gitlab_mr_updated",
      runId: input.runId,
      ts: now(),
      detail: { mrIid: existingMr.iid },
    });
  }

  // V4.1: synthetic task runs still want the MR (each task owns one), but
  // must NOT write a per-run workpad note onto the parent Issue, and must
  // NOT transition the parent Issue's workflow label. Return early after
  // the MR step so the caller can record the MR coordinates on the
  // canonical `TaskRunLink`.
  if (suppressParentIssue) {
    return {
      hadNewCommits: true,
      mergeRequest: handoffMr,
    };
  }

  const marker = `<!-- issuepilot:run:${input.runId} -->`;
  const existingNote = await input.gitlab.findWorkpadNote(input.iid, marker);
  const noteBody = renderNoteBody(input, handoffMr);

  let handoffNoteId: number | undefined;
  if (!existingNote) {
    const note = await input.gitlab.createNote(input.iid, noteBody);
    handoffNoteId = note.id;
  } else {
    await input.gitlab.updateNote(input.iid, existingNote.id, noteBody);
    handoffNoteId = existingNote.id;
  }

  await transitionToHandoff(input);
  return {
    hadNewCommits: true,
    mergeRequest: handoffMr,
    ...(handoffNoteId !== undefined ? { handoffNoteId } : {}),
  };
}

async function transitionToHandoff(input: ReconcileInput): Promise<void> {
  await input.gitlab.transitionLabels(input.iid, {
    add: [input.handoffLabel],
    remove: [input.runningLabel],
  });
  input.onEvent({
    type: "gitlab_labels_transitioned",
    runId: input.runId,
    ts: now(),
    detail: { add: [input.handoffLabel], remove: [input.runningLabel] },
  });
}
